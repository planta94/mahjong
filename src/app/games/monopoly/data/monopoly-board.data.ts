export function getSpaceByIndex(index: number): BoardSpace | undefined {
  return BOARD_SPACE_MAP.get(index);
}

export function getGroupSpaces(group: ColorGroup): BoardSpace[] {
  return MALAYSIA_BOARD_DATA.filter((s) => s.colorGroup === group);
}

export function getNearestTransitIndex(fromPos: number): number {
  const transits = [5, 15, 25, 35];
  for (const t of transits) {
    if (t > fromPos) return t;
  }
  return 5; // Wraps around to KL Sentral
}

export function getNearestUtilityIndex(fromPos: number): number {
  const utilities = [12, 28];
  for (const u of utilities) {
    if (u > fromPos) return u;
  }
  return 12; // Wraps around to TNB
}
